import { NextResponse } from 'next/server';
import prisma from '@/lib/prisma';
import { getSessionUser } from '@/lib/auth';

export async function GET(request: Request) {
  try {
    const user = await getSessionUser();
    if (!user || user.role !== 'ADMIN') {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 403 });
    }

    const { searchParams } = new URL(request.url);
    const startDateStr = searchParams.get('startDate');
    const endDateStr = searchParams.get('endDate');
    const userId = searchParams.get('userId');
    const templateType = searchParams.get('template') || 'simple'; // 'simple' or 'extended'

    const where: {
      status: string;
      userId?: string;
      date?: { gte?: Date; lte?: Date };
    } = {
      status: 'APPROVED', // Only export approved claims
    };

    if (userId) {
      where.userId = userId;
    }

    if (startDateStr || endDateStr) {
      where.date = {};
      if (startDateStr) {
        where.date.gte = new Date(startDateStr);
      }
      if (endDateStr) {
        where.date.lte = new Date(endDateStr);
      }
    }

    const claims = await prisma.claim.findMany({
      where,
      include: {
        account: true,
        user: true,
      },
      orderBy: { date: 'asc' },
    });

    let csvContent = '';
    const headers = templateType === 'extended'
      ? ['Employee', 'Supplier', 'Expense Claim No.', 'Date', 'Due Date', 'Currency', 'Account', 'Description', 'Product', 'Quantity', 'Location', 'Unit Price', 'Discount', 'Tax', 'Reference No.']
      : ['Employee', 'Reference No.', 'Date', 'Due Date', 'Currency', 'Account', 'Item Description', 'Amount', 'Tax', 'Supplier'];

    // Excel CSV UTF-8 Byte Order Mark
    csvContent += '\uFEFF';
    csvContent += headers.map(h => `"${h}"`).join(',') + '\r\n';

    for (const claim of claims) {
      const dateStr = claim.date.toISOString().split('T')[0];
      const employeeName = claim.user.name || claim.user.username;

      const row = templateType === 'extended'
        ? [
            employeeName,
            claim.supplierName,
            '', // Expense Claim No. (autogenerated by Bukku)
            dateStr,
            dateStr, // Due Date
            'MYR',
            claim.account.code, // Account Code (e.g. 6001)
            claim.itemDescription,
            '', // Product
            '1', // Quantity
            '', // Location
            claim.amount.toFixed(2), // Unit Price
            '0', // Discount
            '', // Tax
            claim.referenceNumber // Reference No.
          ]
        : [
            employeeName,
            claim.referenceNumber,
            dateStr,
            dateStr, // Due Date
            'MYR',
            claim.account.code, // Account Code (e.g. 6001)
            claim.itemDescription,
            claim.amount.toFixed(2),
            '', // Tax
            claim.supplierName
          ];

      csvContent += row.map(val => {
        const str = (val === null || val === undefined ? '' : val).toString().replace(/"/g, '""');
        return `"${str}"`;
      }).join(',') + '\r\n';
    }

    const response = new NextResponse(csvContent, {
      headers: {
        'Content-Type': 'text/csv; charset=utf-8',
        'Content-Disposition': `attachment; filename="bukku_expense_claims_${templateType}_${Date.now()}.csv"`,
      },
    });

    return response;
  } catch (error) {
    console.error('Export claims error:', error);
    return NextResponse.json({ error: 'Internal server error' }, { status: 500 });
  }
}
